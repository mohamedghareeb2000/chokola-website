export function buildMenuCategories(products = [], categoryMeta = MENU_CATEGORY_META) {
  const productsByCategory = products.reduce((groups, product) => {
    const categoryProducts = groups.get(product.category) || []
    categoryProducts.push(product)
    groups.set(product.category, categoryProducts)
    return groups
  }, new Map())

  return categoryMeta.map((category) => ({
    ...category,
    products: (productsByCategory.get(category.name) || [])
      .slice()
      .map((product) => ({
        ...product,
        name: product.name || product.title,
      }))
      .sort((a, b) => (a.order || 0) - (b.order || 0)),
  }))
}
